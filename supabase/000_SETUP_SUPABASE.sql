-- Checkout público: visitante pode criar pedido, mas não listar pedidos.
create policy "public create orders"
on public.orders for insert
to anon, authenticated
with check (
  exists (
    select 1 from public.businesses b
    where b.id = orders.business_id and b.is_active = true
  )
);

create policy "business reads orders"
on public.orders for select
to authenticated
using (
  exists (
    select 1 from public.business_members bm
    where bm.business_id = orders.business_id and bm.user_id = auth.uid()
  )
  or exists (
    select 1 from public.businesses b
    where b.id = orders.business_id and b.owner_id = auth.uid()
  )
);

create policy "business updates orders"
on public.orders for update
to authenticated
using (
  exists (
    select 1 from public.business_members bm
    where bm.business_id = orders.business_id and bm.user_id = auth.uid()
  )
  or exists (
    select 1 from public.businesses b
    where b.id = orders.business_id and b.owner_id = auth.uid()
  )
);

create policy "public create order items"
on public.order_items for insert
to anon, authenticated
with check (
  exists (
    select 1 from public.orders o
    join public.businesses b on b.id = o.business_id
    where o.id = order_items.order_id and b.is_active = true
  )
);

create policy "business reads order items"
on public.order_items for select
to authenticated
using (
  exists (
    select 1 from public.orders o
    left join public.business_members bm
      on bm.business_id = o.business_id and bm.user_id = auth.uid()
    left join public.businesses b
      on b.id = o.business_id
    where o.id = order_items.order_id
      and (bm.user_id = auth.uid() or b.owner_id = auth.uid())
  )
);


